module boozer_regular
    !> Regular near-axis evaluation of a Boozer field in the Cartesian chart
    !> (X, Y, phi), X = rho cos(theta), Y = rho sin(theta), s = rho**2.
    !>
    !> |B| = F0 + X F1c + Y F1s + s F20 + (X**2 - Y**2) F2c + 2 X Y F2s
    !>       + rho**3 R(rho, theta, phi),
    !> with axis functions F*(phi), B_theta = I = s i(rho),
    !> B_phi = G = G0 + s g(rho), A_phi = A0 + s a(rho) and A_theta = torflux s.
    !>
    !> The axis value is theta-independent and the axis gradient and Hessian
    !> are the exact m = 0, 1, 2 Taylor terms by construction; rho**3 R is C^2.
    !> The pointwise chain rule from the polar spline jets to (X, Y, phi) and
    !> the quotients h = B_k/|B| are FortSym leaves generated by
    !> gen/gen_boozer_regular.f90 and contain no division by rho.
    use interpolate, only: BatchSplineData1D, BatchSplineData3D, &
                           construct_batch_splines_1d, construct_batch_splines_3d, &
                           destroy_batch_splines_1d, destroy_batch_splines_3d, &
                           evaluate_batch_splines_1d_der, &
                           evaluate_batch_splines_1d_der2, &
                           evaluate_batch_splines_3d_der, &
                           evaluate_batch_splines_3d_der2
    use, intrinsic :: iso_fortran_env, only: dp => real64

    implicit none
    private

    public :: regular_field_t, boozer_regular_t
    public :: REGULAR_VALUE, REGULAR_FIRST, REGULAR_SECOND
    public :: build_boozer_regular
    public :: boozer_regular_field, boozer_regular_enabled
    public :: set_boozer_regular_enabled, eval_boozer_regular

    !> Evaluation modes: values; values and first derivatives; values, first
    !> and second derivatives. Components above the requested mode are unset.
    integer, parameter :: REGULAR_VALUE = 0
    integer, parameter :: REGULAR_FIRST = 1
    integer, parameter :: REGULAR_SECOND = 2

    real(dp), parameter :: TWOPI = 6.283185307179586476925286766559_dp

    !> Field values in (X, Y, phi). First derivatives are ordered (X, Y, phi);
    !> second derivatives (XX, XY, Xphi, YY, Yphi, phiphi). h_k = B_k/|B|.
    type :: regular_field_t
        real(dp) :: Ath = 0.0_dp, Aph = 0.0_dp
        real(dp) :: hth = 0.0_dp, hph = 0.0_dp, Bmod = 0.0_dp
        real(dp) :: dAth(3) = 0.0_dp, dAph(3) = 0.0_dp
        real(dp) :: dhth(3) = 0.0_dp, dhph(3) = 0.0_dp, dBmod(3) = 0.0_dp
        real(dp) :: d2Ath(6) = 0.0_dp, d2Aph(6) = 0.0_dp
        real(dp) :: d2hth(6) = 0.0_dp, d2hph(6) = 0.0_dp, d2Bmod(6) = 0.0_dp
    end type regular_field_t

    type :: boozer_regular_t
        logical :: ready = .false.
        integer :: nfp = 1
        real(dp) :: torflux = 0.0_dp
        !> Poloidal current G and A_phi at the axis.
        real(dp) :: g0 = 0.0_dp, a0 = 0.0_dp
        !> F0, F1c, F1s, F20, F2c, F2s over one field period in phi.
        type(BatchSplineData1D) :: axis
        !> R over (rho, theta, phi).
        type(BatchSplineData3D) :: remainder
        !> i, g and a over rho.
        type(BatchSplineData1D) :: flux
    contains
        procedure :: eval => boozer_regular_eval
        procedure :: destroy => boozer_regular_destroy
    end type boozer_regular_t

    type(boozer_regular_t), save :: boozer_regular_field
    !> Building the regular field costs a second 3D spline, so the Boozer
    !> builders construct it only on request.
    logical, save :: boozer_regular_enabled = .false.

contains

    subroutine set_boozer_regular_enabled(enabled)
        logical, intent(in) :: enabled

        boozer_regular_enabled = enabled
    end subroutine set_boozer_regular_enabled

    !> Evaluate the module-level regular field built by the Boozer builders.
    subroutine eval_boozer_regular(x, y, phi, mode, f)
        real(dp), intent(in) :: x, y, phi
        integer, intent(in) :: mode
        type(regular_field_t), intent(inout) :: f

        if (.not. boozer_regular_field%ready) &
            error stop "eval_boozer_regular: regular field not built"
        call boozer_regular_field%eval(x, y, phi, mode, f)
    end subroutine eval_boozer_regular

    !> Build the regular representation from Boozer grid data.
    !>
    !> rho holds the true radial abscissae of the data; nodes 2: must be
    !> uniform. When the node before rho(2) lies at the axis (within h/4), the
    !> first node is treated as the axis node: it only enters the m = 0
    !> extrapolation, at its true abscissa rho(1). bmod is (n_rho, n_theta,
    !> n_phi) on endpoint-included periodic grids over 2 pi and 2 pi/nfp.
    !> aphi is the A_phi(s) spline; it is resampled onto the rho nodes.
    subroutine build_boozer_regular(field, rho, bmod, b_theta, b_phi, aphi, &
                                    torflux, nfp, order_rho, order_angle)
        type(boozer_regular_t), intent(inout) :: field
        real(dp), intent(in) :: rho(:)
        real(dp), intent(in) :: bmod(:, :, :)
        real(dp), intent(in) :: b_theta(:), b_phi(:)
        type(BatchSplineData1D), intent(in) :: aphi
        real(dp), intent(in) :: torflux
        integer, intent(in) :: nfp, order_rho, order_angle

        real(dp), allocatable :: rem(:, :, :, :), axis(:, :), flux(:, :)
        real(dp), allocatable :: cos_t(:, :), sin_t(:, :)
        real(dp) :: h, x0, w0(3), v0(3), w1(3), a0(3), ac(3, 2), as(3, 2), t
        real(dp) :: ap(1), dap(1)
        integer :: n_rho, n_theta, n_phi, i, j, k, m, i1, n_fourier
        logical :: axis_node

        n_rho = size(bmod, 1)
        n_theta = size(bmod, 2)
        n_phi = size(bmod, 3)
        if (n_rho < 6) error stop "build_boozer_regular: need at least 6 radial nodes"
        if (size(rho) /= n_rho .or. size(b_theta) /= n_rho .or. &
            size(b_phi) /= n_rho) error stop "build_boozer_regular: size mismatch"

        call field%destroy()

        h = rho(3) - rho(2)
        x0 = rho(2) - h
        axis_node = x0 < 0.25_dp*h
        if (axis_node) then
            x0 = 0.0_dp
            i1 = 2
        else
            i1 = 1
        end if

        w0 = extrapolation_weights(rho(1:3)**2)
        v0 = slope_weights(rho(1:3)**2)
        w1 = extrapolation_weights(rho(i1:i1 + 2)**2)

        n_fourier = n_theta - 1
        allocate (cos_t(n_theta, 2), sin_t(n_theta, 2))
        do m = 1, 2
            do j = 1, n_theta
                t = TWOPI*real(m*(j - 1), dp)/real(n_fourier, dp)
                cos_t(j, m) = cos(t)
                sin_t(j, m) = sin(t)
            end do
        end do

        allocate (rem(n_rho, n_theta, n_phi, 1), axis(n_phi, 6), flux(n_rho, 3))
        do k = 1, n_phi
            do i = 1, 3
                a0(i) = sum(bmod(i, 1:n_fourier, k))/real(n_fourier, dp)
                do m = 1, 2
                    ac(i, m) = 2.0_dp*sum(bmod(i1 + i - 1, 1:n_fourier, k)* &
                                          cos_t(1:n_fourier, m))/real(n_fourier, dp)
                    as(i, m) = 2.0_dp*sum(bmod(i1 + i - 1, 1:n_fourier, k)* &
                                          sin_t(1:n_fourier, m))/real(n_fourier, dp)
                end do
            end do
            axis(k, 1) = sum(w0*a0)
            axis(k, 2) = sum(w1*ac(:, 1)/rho(i1:i1 + 2))
            axis(k, 3) = sum(w1*as(:, 1)/rho(i1:i1 + 2))
            axis(k, 4) = sum(v0*a0)
            axis(k, 5) = sum(w1*ac(:, 2)/rho(i1:i1 + 2)**2)
            axis(k, 6) = sum(w1*as(:, 2)/rho(i1:i1 + 2)**2)
            do j = 1, n_theta
                do i = i1, n_rho
                    rem(i, j, k, 1) = (bmod(i, j, k) - axis(k, 1) &
                                       - rho(i)*(cos_t(j, 1)*axis(k, 2) &
                                                 + sin_t(j, 1)*axis(k, 3)) &
                                       - rho(i)**2*(axis(k, 4) &
                                                    + cos_t(j, 2)*axis(k, 5) &
                                                    + sin_t(j, 2)*axis(k, 6))) &
                                      /rho(i)**3
                end do
            end do
        end do
        axis(n_phi, :) = axis(1, :)
        rem(:, n_theta, :, 1) = rem(:, 1, :, 1)
        rem(:, :, n_phi, 1) = rem(:, :, 1, 1)
        if (axis_node) rem(1, :, :, 1) = 3.0_dp*rem(2, :, :, 1) &
                                         - 3.0_dp*rem(3, :, :, 1) + rem(4, :, :, 1)

        field%g0 = sum(w0*b_phi(1:3))
        call evaluate_batch_splines_1d_der(aphi, 0.0_dp, ap, dap)
        field%a0 = ap(1)
        do i = i1, n_rho
            flux(i, 1) = b_theta(i)/rho(i)**2
            flux(i, 2) = (b_phi(i) - field%g0)/rho(i)**2
            call evaluate_batch_splines_1d_der(aphi, rho(i)**2, ap, dap)
            flux(i, 3) = (ap(1) - field%a0)/rho(i)**2
        end do
        if (axis_node) then
            flux(1, 1:2) = 3.0_dp*flux(2, 1:2) - 3.0_dp*flux(3, 1:2) + flux(4, 1:2)
            call evaluate_batch_splines_1d_der(aphi, 0.0_dp, ap, dap)
            flux(1, 3) = dap(1)
        end if

        call construct_batch_splines_1d(0.0_dp, TWOPI/real(nfp, dp), axis, &
                                        order_angle, .true., field%axis)
        call construct_batch_splines_3d([x0, 0.0_dp, 0.0_dp], &
                                        [x0 + h*real(n_rho - 1, dp), TWOPI, &
                                         TWOPI/real(nfp, dp)], rem, &
                                        [order_rho, order_angle, order_angle], &
                                        [.false., .true., .true.], field%remainder)
        call construct_batch_splines_1d(x0, x0 + h*real(n_rho - 1, dp), flux, &
                                        order_rho, .false., field%flux)
        field%torflux = torflux
        field%nfp = nfp
        field%ready = .true.
    end subroutine build_boozer_regular

    !> Lagrange weights that extrapolate a quadratic in s to s = 0.
    pure function extrapolation_weights(s) result(w)
        real(dp), intent(in) :: s(3)
        real(dp) :: w(3)

        w(1) = s(2)*s(3)/((s(1) - s(2))*(s(1) - s(3)))
        w(2) = s(1)*s(3)/((s(2) - s(1))*(s(2) - s(3)))
        w(3) = s(1)*s(2)/((s(3) - s(1))*(s(3) - s(2)))
    end function extrapolation_weights

    !> Lagrange weights for the slope at s = 0 of the quadratic through s.
    pure function slope_weights(s) result(v)
        real(dp), intent(in) :: s(3)
        real(dp) :: v(3)

        v(1) = -(s(2) + s(3))/((s(1) - s(2))*(s(1) - s(3)))
        v(2) = -(s(1) + s(3))/((s(2) - s(1))*(s(2) - s(3)))
        v(3) = -(s(1) + s(2))/((s(3) - s(1))*(s(3) - s(2)))
    end function slope_weights

    !> Axis jets in phi (periodic) and flux jets in rho with first
    !> derivatives, both 1D splines in one pass. Private to keep the public
    !> library evaluator, and thus existing results, unchanged.
    pure subroutine axis_flux_d1(axis, flux, phi, rho, ax, dax, fl, dfl)
        type(BatchSplineData1D), intent(in) :: axis, flux
        real(dp), intent(in) :: phi, rho
        real(dp), intent(out) :: ax(6), dax(6), fl(3), dfl(3)

        real(dp) :: t, period, xa, xf, ca(6, 0:5), cf(3, 0:5)
        integer :: ja, jf, k, na, nf

        na = axis%order
        nf = flux%order
        period = axis%h_step*real(axis%num_points - 1, dp)
        t = phi - axis%x_min
        if (t < 0.0_dp .or. t >= period) t = modulo(t, period)
        t = t/axis%h_step
        ja = max(0, min(axis%num_points - 2, int(t)))
        xa = (t - real(ja, dp))*axis%h_step
        t = (rho - flux%x_min)/flux%h_step
        jf = max(0, min(flux%num_points - 2, int(t)))
        xf = (t - real(jf, dp))*flux%h_step

        ca(:, 0:na) = axis%coeff(:, 0:na, ja + 1)
        cf(:, 0:nf) = flux%coeff(:, 0:nf, jf + 1)
        ax = ca(:, na)
        dax = real(na, dp)*ca(:, na)
        fl = cf(:, nf)
        dfl = real(nf, dp)*cf(:, nf)
        do k = max(na, nf) - 1, 1, -1
            if (k < na) dax = real(k, dp)*ca(:, k) + xa*dax
            if (k < nf) dfl = real(k, dp)*cf(:, k) + xf*dfl
        end do
        do k = max(na, nf) - 1, 0, -1
            if (k < na) ax = ca(:, k) + xa*ax
            if (k < nf) fl = cf(:, k) + xf*fl
        end do
    end subroutine axis_flux_d1

    subroutine boozer_regular_destroy(self)
        class(boozer_regular_t), intent(inout) :: self

        if (allocated(self%axis%coeff)) call destroy_batch_splines_1d(self%axis)
        if (allocated(self%remainder%coeff)) &
            call destroy_batch_splines_3d(self%remainder)
        if (allocated(self%flux%coeff)) call destroy_batch_splines_1d(self%flux)
        self%ready = .false.
    end subroutine boozer_regular_destroy

    !> Evaluate at Cartesian (x, y) = rho (cos, sin) theta_B and phi = phi_B.
    subroutine boozer_regular_eval(self, x, y, phi, mode, f)
        class(boozer_regular_t), intent(in) :: self
        real(dp), intent(in) :: x, y, phi
        integer, intent(in) :: mode
        type(regular_field_t), intent(inout) :: f

        real(dp) :: s, rho, c, sn, theta, q(3)
        real(dp) :: ax(6), dax(6), d2ax(6)
        real(dp) :: r(1), dr(3, 1), d2r(6, 1)
        real(dp) :: fl(3), dfl(3), d2fl(3)
        real(dp) :: bi(6), bg(6)

        s = x*x + y*y
        rho = sqrt(s)
        if (rho > 0.0_dp) then
            c = x/rho
            sn = y/rho
            theta = atan2(y, x)
            if (theta < 0.0_dp) theta = theta + TWOPI
        else
            c = 1.0_dp
            sn = 0.0_dp
            theta = 0.0_dp
        end if
        q = [rho, theta, phi]

        if (mode < REGULAR_SECOND) then
            call evaluate_batch_splines_3d_der(self%remainder, q, r, dr)
            call axis_flux_d1(self%axis, self%flux, phi, rho, ax, dax, fl, dfl)
        else
            call evaluate_batch_splines_1d_der2(self%axis, phi, ax, dax, d2ax)
            call evaluate_batch_splines_3d_der2(self%remainder, q, r, dr, d2r)
            call evaluate_batch_splines_1d_der2(self%flux, rho, fl, dfl, d2fl)
        end if

        select case (mode)
        case (REGULAR_VALUE)
            call boozer_regular_polar_d0(rho, c, sn, self%torflux, ax(1), ax(2), &
                                         ax(3), ax(4), ax(5), ax(6), r(1), fl(1), &
                                         self%g0, fl(2), self%a0, fl(3), &
                                         f%Bmod, bi(1), bg(1), f%Aph, f%Ath)
            f%hth = bi(1)/f%Bmod
            f%hph = bg(1)/f%Bmod
        case (REGULAR_FIRST)
            call boozer_regular_polar_d1(rho, c, sn, self%torflux, ax(1), ax(2), &
                                         ax(3), ax(4), ax(5), ax(6), r(1), fl(1), &
                                         self%g0, fl(2), self%a0, fl(3), dax(1), &
                                         dax(2), dax(3), dax(4), dax(5), dax(6), &
                                         dr(1, 1), &
                                         dr(2, 1), dr(3, 1), dfl(1), dfl(2), dfl(3), &
                                         f%Bmod, f%dBmod(1), f%dBmod(2), f%dBmod(3), &
                                         bi(1), bi(2), bi(3), bg(1), bg(2), bg(3), &
                                         f%Aph, f%dAph(1), f%dAph(2), &
                                         f%Ath, f%dAth(1), f%dAth(2))
            f%dAph(3) = 0.0_dp
            f%dAth(3) = 0.0_dp
            call boozer_regular_quotient_d1(bi(1), bi(2), bi(3), bg(1), bg(2), &
                                            bg(3), f%Bmod, f%dBmod(1), &
                                            f%dBmod(2), f%dBmod(3), f%hth, &
                                            f%dhth(1), f%dhth(2), f%dhth(3), &
                                            f%hph, f%dhph(1), f%dhph(2), f%dhph(3))
        case (REGULAR_SECOND)
            call boozer_regular_polar_d2(rho, c, sn, self%torflux, ax(1), ax(2), &
                                         ax(3), ax(4), ax(5), ax(6), r(1), fl(1), &
                                         self%g0, fl(2), self%a0, fl(3), dax(1), &
                                         dax(2), dax(3), dax(4), dax(5), dax(6), &
                                         dr(1, 1), &
                                         dr(2, 1), dr(3, 1), dfl(1), dfl(2), dfl(3), &
                                         d2ax(1), d2ax(2), d2ax(3), d2ax(4), &
                                         d2ax(5), d2ax(6), d2r(1, 1), d2r(2, 1), &
                                         d2r(3, 1), d2r(4, 1), d2r(5, 1), d2r(6, 1), &
                                         d2fl(1), d2fl(2), d2fl(3), &
                                         f%Bmod, f%dBmod(1), f%dBmod(2), f%dBmod(3), &
                                         f%d2Bmod(1), f%d2Bmod(2), f%d2Bmod(3), &
                                         f%d2Bmod(4), f%d2Bmod(5), f%d2Bmod(6), &
                                         bi(1), bi(2), bi(3), bi(4), bi(5), bi(6), &
                                         bg(1), bg(2), bg(3), bg(4), bg(5), bg(6), &
                                         f%Aph, f%dAph(1), f%dAph(2), f%d2Aph(1), &
                                         f%d2Aph(2), f%d2Aph(4), &
                                         f%Ath, f%dAth(1), f%dAth(2), f%d2Ath(1), &
                                         f%d2Ath(2), f%d2Ath(4))
            f%dAph(3) = 0.0_dp
            f%dAth(3) = 0.0_dp
            f%d2Aph(3) = 0.0_dp
            f%d2Aph(5:6) = 0.0_dp
            f%d2Ath(3) = 0.0_dp
            f%d2Ath(5:6) = 0.0_dp
            call boozer_regular_quotient_d2(bi(1), bi(2), bi(3), bi(4), bi(5), &
                                            bi(6), bg(1), bg(2), bg(3), bg(4), &
                                            bg(5), bg(6), f%Bmod, f%dBmod(1), &
                                            f%dBmod(2), f%dBmod(3), f%d2Bmod(1), &
                                            f%d2Bmod(2), f%d2Bmod(3), f%d2Bmod(4), &
                                            f%d2Bmod(5), f%d2Bmod(6), f%hth, &
                                            f%dhth(1), f%dhth(2), f%dhth(3), &
                                            f%d2hth(1), f%d2hth(2), f%d2hth(3), &
                                            f%d2hth(4), f%d2hth(5), f%d2hth(6), &
                                            f%hph, f%dhph(1), f%dhph(2), f%dhph(3), &
                                            f%d2hph(1), f%d2hph(2), f%d2hph(3), &
                                            f%d2hph(4), f%d2hph(5), f%d2hph(6))
        case default
            error stop "boozer_regular_eval: mode must be 0, 1 or 2"
        end select
    end subroutine boozer_regular_eval

    include 'generated/boozer_regular_leaves.inc'

end module boozer_regular
