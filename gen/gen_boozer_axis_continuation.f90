!> C2 continuation of one scalar Fourier primary below its first radial knot.
!> With x=s/a and q=m/2, c(s)=x**q P(x), where P is quadratic in s.
!> The endpoint jet is [c(a), a*c'(a), a**2*c''(a)]. This generates its
!> linear map to [c(s), a*c'(s), a**2*c''(s)] and proves the C2 join.
program gen_boozer_axis_continuation
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, operator(+), operator(-), &
                            operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use fortsym_subs, only: subs
    use fortsym_check, only: suite_t, suite_begin, suite_end, check_identity
    use libneo_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(arena_t), target :: arena
    type(leaf_writer_t) :: w
    type(suite_t) :: proof
    type(expr_t) :: q, x, u0, u1, u2, one, zero
    type(expr_t) :: p(3), jets(3, 3), roots(9), endpoint, expected
    character(4), parameter :: inputs(5) = [character(4) :: &
        'q', 'x', 'u0', 'u1', 'u2']
    character(4), parameter :: outputs(9) = [character(4) :: &
        'w11', 'w12', 'w13', 'w21', 'w22', 'w23', 'w31', 'w32', 'w33']
    character(256) :: path, receipt
    character(40) :: label
    integer :: i, j, k

    path = 'src/generated/boozer_axis_continuation_leaves.inc'
    receipt = 'boozer_axis_continuation_proof.json'
    if (command_argument_count() >= 1) call get_command_argument(1, path)
    if (command_argument_count() >= 2) call get_command_argument(2, receipt)
    call arena%init()
    q = sym(arena, 'q')
    x = sym(arena, 'x')
    u0 = sym(arena, 'u0')
    u1 = sym(arena, 'u1')
    u2 = sym(arena, 'u2')
    one = 1 + 0*x
    zero = 0*x
    p(1) = 1 - q*(x - 1) + q*(q + 1)*(x - 1)**2/2
    p(2) = (x - 1) - q*(x - 1)**2
    p(3) = (x - 1)**2/2

    call w%open(arena, 'gen_boozer_axis_continuation', trim(path))
    call suite_begin(proof, 'scalar Fourier primary C2 axis continuation')
    do j = 1, 3
        jets(1, j) = u0*p(j)
        jets(2, j) = q*u1*p(j) + u0*diff(p(j), x)
        jets(3, j) = q*(q - 1)*u2*p(j) + &
                     2*q*u1*diff(p(j), x) + u0*diff(diff(p(j), x), x)
        write (label, '(a,i1)') 'first jet chain rule, column ', j
        call check_identity(proof, w%engine, trim(label), &
                            derivative(jets(1, j)) - jets(2, j))
        write (label, '(a,i1)') 'second jet chain rule, column ', j
        call check_identity(proof, w%engine, trim(label), &
                            derivative(jets(2, j)) - jets(3, j))
        do i = 1, 3
            endpoint = subs(jets(i, j), x, one)
            endpoint = subs(endpoint, u0, one)
            endpoint = subs(endpoint, u1, one)
            endpoint = subs(endpoint, u2, one)
            expected = zero
            if (i == j) expected = one
            write (label, '(a,i1,a,i1)') 'C2 endpoint row ', i, ', column ', j
            call check_identity(proof, w%engine, trim(label), endpoint - expected)
        end do
        write (label, '(a,i1)') 'quadratic regular amplitude, column ', j
        call check_identity(proof, w%engine, trim(label), &
                            diff(diff(diff(p(j), x), x), x))
    end do
    call suite_end(proof, trim(receipt))
    k = 0
    do i = 1, 3
        do j = 1, 3
            k = k + 1
            roots(k) = w%simplify(jets(i, j))
        end do
    end do
    call w%line('! Generated by gen/gen_boozer_axis_continuation.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! Scalar primaries only. Domain: integer m >= 2 and 0 < x <= 1.')
    call w%line('! w maps [c(a),a*c''(a),a**2*c''''(a)] to the same jet at s=x*a.')
    call w%line('pure subroutine boozer_axis_continuation_weights(m, x, w)')
    call w%line('    use, intrinsic :: iso_fortran_env, only: dp => real64')
    call w%line('    implicit none')
    call w%line('    integer, intent(in) :: m')
    call w%line('    real(dp), intent(in) :: x')
    call w%line('    real(dp), intent(out) :: w(3, 3)')
    call w%line('    real(dp) :: q, u0, u1, u2')
    call w%line('    q = 0.5_dp*real(m, dp)')
    call w%line('    u0 = x**q')
    call w%line('    u1 = x**(q - 1)')
    call w%line('    u2 = 0.0_dp')
    call w%line('    if (m > 2) u2 = x**(q - 2)')
    call w%line('    call boozer_axis_continuation_leaf(q, x, u0, u1, u2, &')
    call w%line('        w(1, 1), w(1, 2), w(1, 3), w(2, 1), w(2, 2), w(2, 3), &')
    call w%line('        w(3, 1), w(3, 2), w(3, 3))')
    call w%line('end subroutine boozer_axis_continuation_weights')
    call w%emit('boozer_axis_continuation_leaf', inputs, outputs, roots)
    call w%close()

contains

    function derivative(f) result(df)
        type(expr_t), intent(in) :: f
        type(expr_t) :: df

        ! d(x**q)/dx=q*x**(q-1) and d(x**(q-1))/dx=(q-1)*x**(q-2).
        df = diff(f, x) + q*u1*diff(f, u0) + (q - 1)*u2*diff(f, u1)
    end function derivative
end program gen_boozer_axis_continuation
