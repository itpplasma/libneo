program gen_coordinate_jets
    use fortsym_expr, only: expr_t, sym, func, sin, cos, sqrt, &
                            operator(+), operator(-), operator(*), operator(/)
    use fortsym_diff, only: diff
    use fortsym_jet, only: bind, suffixed, listed
    use fortsym_string, only: words, itoa
    use libneo_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: writer
    type(expr_t) :: s, t, p, x, y, rotated(2), e(3), h(3), product
    type(expr_t) :: ji, jj, dji, basis, dbasis
    type(expr_t) :: xy(2), cyl(3), cart(3), radius, magnitude, unit(3)
    character(256) :: path
    integer :: i

    path = 'src/generated/coordinate_jets_leaves.inc'
    if (command_argument_count() > 0) call get_command_argument(1, path)
    s = sym('s'); t = sym('t')
    p = func('P', [s, t]); x = func('X', [s, t]); y = func('Y', [s, t])
    rotated = [cos(p)*x - sin(p)*y, sin(p)*x + cos(p)*y]
    ! Jets in (s, t) are p, pi, pj, pij and likewise for x and y.
    call bind(p, suffixed('p', ['i', 'j'], separator=''))
    call bind(x, suffixed('x', ['i', 'j'], separator=''))
    call bind(y, suffixed('y', ['i', 'j'], separator=''))
    call writer%open('gen_coordinate_jets', trim(path))
    call writer%line('! Generated by gen/gen_coordinate_jets.f90; do not edit.')
    call writer%line('! FortSym revision: '//fortsym_revision)
    call writer%emit('rotate_pair_value', &
                   [character(3) :: 'p', 'x', 'y'], [character(3) :: 'rx', 'ry'], rotated)
    call writer%emit('rotate_pair_der', &
                     [character(3) :: 'p', 'x', 'y', 'pi', 'xi', 'yi'], &
                     [character(3) :: 'rx', 'ry', 'rxi', 'ryi'], &
                     [rotated, diff(rotated(1), s), diff(rotated(2), s)])
    call writer%emit('rotate_pair_der2', &
                     [character(3) :: 'p', 'x', 'y', 'pi', 'xi', 'yi', &
                      'pj', 'xj', 'yj', 'pij', 'xij', 'yij'], &
             [character(4) :: 'rx', 'ry', 'rxi', 'ryi', 'rxj', 'ryj', 'rxij', 'ryij'], &
                     [rotated, diff(rotated(1), s), diff(rotated(2), s), &
                      diff(rotated(1), t), diff(rotated(2), t), &
                      diff(diff(rotated(1), s), t), diff(diff(rotated(2), s), t)])
    do i = 1, 3
        e(i) = func('E'//itoa(i), [s]); h(i) = func('H'//itoa(i), [s])
        call bind(e(i), listed(words('e'//itoa(i)//' de'//itoa(i))))
        call bind(h(i), listed(words('h'//itoa(i)//' dh'//itoa(i))))
    end do
    product = e(1)*h(1) + e(2)*h(2) + e(3)*h(3)
    call writer%emit('pullback_value', &
                     [character(3) :: 'e1', 'e2', 'e3', 'h1', 'h2', 'h3'], &
                     [character(3) :: 'v'], [product])
    call writer%emit('pullback_der', &
                     [character(3) :: 'e1', 'e2', 'e3', 'h1', 'h2', 'h3', &
                      'de1', 'de2', 'de3', 'dh1', 'dh2', 'dh3'], &
                     [character(3) :: 'v', 'dv'], [product, diff(product, s)])
    basis = sym('e'); dbasis = sym('de')
    ji = sym('ji'); jj = sym('jj'); dji = sym('dji')
    call writer%emit('diagonal_basis_der', &
                     [character(3) :: 'e', 'de', 'ji', 'jj', 'dji'], &
                     [character(3) :: 'v', 'dv'], [basis*ji, dbasis*ji*jj + basis*dji])
    ! Cylindrical coordinate components of physical B are interpolated before
    ! normalization. Derivatives include the physical position and the norm.
    xy = [func('CX', [s]), func('CY', [s])]
    cyl = [func('BR', [s]), func('BP', [s]), func('BZ', [s])]
    radius = sqrt(xy(1)*xy(1) + xy(2)*xy(2))
    cart = [xy(1)/radius*cyl(1) - xy(2)*cyl(2), &
            xy(2)/radius*cyl(1) + xy(1)*cyl(2), cyl(3)]
    magnitude = sqrt(cart(1)*cart(1) + cart(2)*cart(2) + cart(3)*cart(3))
    do i = 1, 3
        unit(i) = cart(i)/magnitude
    end do
    call bind(xy(1), listed(words('x dx')))
    call bind(xy(2), listed(words('y dy')))
    call bind(cyl(1), listed(words('br dbr')))
    call bind(cyl(2), listed(words('bp dbp')))
    call bind(cyl(3), listed(words('bz dbz')))
    call writer%emit('cylindrical_direction_value', &
                     [character(3) :: 'x', 'y', 'br', 'bp', 'bz'], &
                     [character(3) :: 'hx', 'hy', 'hz'], unit)
    call writer%emit('cylindrical_direction_der', &
                     [character(3) :: 'x', 'y', 'br', 'bp', 'bz', &
                      'dx', 'dy', 'dbr', 'dbp', 'dbz'], &
                     [character(3) :: 'hx', 'hy', 'hz', 'dhx', 'dhy', 'dhz'], &
                     [unit, diff(unit(1), s), diff(unit(2), s), diff(unit(3), s)])
    call writer%close()
end program gen_coordinate_jets
