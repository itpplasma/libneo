!> Manufactured frozen-current solution: an azimuthal current in a ball of
!> radius a about a point c, axis along z.  With d = x - c, r = |d| and
!> A = h(r) z x d,
!>     h = m (35/8 - 21/4 (r/a)^2 + 15/8 (r/a)^4)/a^3  (r < a),
!>     h = m/r^3                                       (r >= a),
!> A is the potential of a magnetic dipole m z outside the ball; h r and its
!> first two radial derivatives are continuous at r = a, so the current
!> curl curl A is continuous and vanishes outside.  B = curl A is derived
!> here.  Inputs are the Cartesian components of d, m and a; outputs the
!> Cartesian components of A and B.
program gen_frozen_current_mms
    use fortsym_expr, only: expr_t, sym, sqrt, operator(+), operator(-), &
                            operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use libneo_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    character(256) :: path
    type(leaf_writer_t) :: w

    path = 'src/generated/frozen_current_mms_leaves.inc'
    if (command_argument_count() >= 1) call get_command_argument(1, path)
    call w%open('gen_frozen_current_mms', trim(path))
    call w%line('! Generated by gen/gen_frozen_current_mms.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! Potential and field of a ball current with a dipole exterior,')
    call w%line('! included by the frozen-current tests.')
    call ball_leaf('mms_ball_inner', .true.)
    call ball_leaf('mms_ball_outer', .false.)
    call w%close()

contains

    subroutine ball_leaf(name, inner)
        character(*), intent(in) :: name
        logical, intent(in) :: inner
        character(8), parameter :: inputs(5) = [character(8) :: 'dx', 'dy', 'dz', &
                                                                                 'm', 'a']
        character(8), parameter :: outputs(6) = [character(8) :: 'ax', 'ay', 'az', &
                                                                         'bx', 'by', 'bz']
        type(expr_t) :: d(3), m, a, r2, h, pot(3), f(6)
        integer :: k

        do k = 1, 3
            d(k) = sym(trim(inputs(k)))
        end do
        m = sym('m')
        a = sym('a')
        r2 = d(1)**2 + d(2)**2 + d(3)**2
        if (inner) then
            h = m*(35*a**4 - 42*r2*a**2 + 15*r2**2)/(8*a**7)
        else
            h = m/(r2*sqrt(r2))
        end if
        pot(1) = -h*d(2)
        pot(2) = h*d(1)
        pot(3) = 0*h
        f(1:3) = pot
        f(4) = diff(pot(3), d(2)) - diff(pot(2), d(3))
        f(5) = diff(pot(1), d(3)) - diff(pot(3), d(1))
        f(6) = diff(pot(2), d(1)) - diff(pot(1), d(2))
        do k = 1, 6
            f(k) = w%simplify(f(k))
        end do
        call w%emit(name, inputs, outputs, f)
    end subroutine ball_leaf
end program gen_frozen_current_mms
