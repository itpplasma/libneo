!> Pointwise field kernel of the VMEC -> Boozer transform and its Jacobian.
!>
!> At one point of the VMEC angle grid the transform needs |B| and the
!> Boozer generating components
!>     bt = B_vartheta (1 + lambda_theta),
!>     bp = B_varphi + B_vartheta lambda_varphi,
!> where B_vartheta and B_varphi are covariant components in symmetry flux
!> coordinates. They follow from R, Z, lambda and their VMEC-coordinate
!> derivatives exactly as in spline_vmec_sub/compute_field_components:
!>     g_V = Jacobian metric of (R, varphi, Z) in (s, theta, varphi),
!>     sqrt(g) = R (R_t Z_s - R_s Z_t) / (1 + lambda_t),
!>     g = C^T g_V C with C(2,:) = (-lambda_s, 1, -lambda_p)/(1 + lambda_t),
!>     B^vartheta = -A_phi'/sqrt(g), B^varphi = A_theta'/sqrt(g).
!> lambda_s drops out of g_22, g_23 and g_33. The leaf returns the three
!> outputs and their partial derivatives with respect to the ten varying
!> inputs (r, rs, rt, rp, zs, zt, zp, lt, lp, aphis); athetas = A_theta' is
!> the fixed toroidal-flux scale.
program gen_boozer_field_jacobian
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, sqrt, operator(+), operator(-), &
                            operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use libneo_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    integer, parameter :: nin = 10
    character(8), parameter :: inputs(nin) = [character(8) :: 'r', 'rs', 'rt', &
        'rp', 'zs', 'zt', 'zp', 'lt', 'lp', 'aphis']
    character(8), parameter :: outputs(3) = [character(8) :: 'b', 'bt', 'bp']
    type(leaf_writer_t) :: w
    type(arena_t), target :: arena
    type(expr_t) :: x(nin), athetas, cj, gv22, gv23, gv33, g22, g23, g33
    type(expr_t) :: sqg, bctr_t, bctr_p, bcov_t, bcov_p, f(3)
    type(expr_t) :: roots(3*(nin + 1))
    character(16) :: names(3*(nin + 1))
    character(256) :: path
    integer :: i, k, n

    path = 'src/generated/boozer_field_jacobian_leaves.inc'
    if (command_argument_count() >= 1) call get_command_argument(1, path)

    call arena%init()
    do k = 1, nin
        x(k) = sym(arena, trim(inputs(k)))
    end do
    athetas = sym(arena, 'athetas')
    associate (r => x(1), rs => x(2), rt => x(3), rp => x(4), zs => x(5), &
               zt => x(6), zp => x(7), lt => x(8), lp => x(9), aphis => x(10))
        cj = 1/(1 + lt)
        gv22 = rt**2 + zt**2
        gv23 = rt*rp + zt*zp
        gv33 = r**2 + rp**2 + zp**2
        g22 = cj**2*gv22
        g23 = cj*(gv23 - lp*cj*gv22)
        g33 = lp**2*cj**2*gv22 - 2*lp*cj*gv23 + gv33
        sqg = r*(rt*zs - rs*zt)*cj
        bctr_t = -aphis/sqg
        bctr_p = athetas/sqg
        bcov_t = g22*bctr_t + g23*bctr_p
        bcov_p = g23*bctr_t + g33*bctr_p
        f(1) = sqrt(bctr_t*bcov_t + bctr_p*bcov_p)
        f(2) = bcov_t*(1 + lt)
        f(3) = bcov_p + bcov_t*lp
    end associate

    call w%open(arena, 'gen_boozer_field_jacobian', trim(path))
    n = 0
    do i = 1, 3
        n = n + 1
        roots(n) = w%simplify(f(i))
        names(n) = outputs(i)
        do k = 1, nin
            n = n + 1
            roots(n) = w%simplify(diff(f(i), x(k)))
            names(n) = trim(outputs(i))//'_'//trim(inputs(k))
        end do
    end do

    call w%line('! Generated by gen/gen_boozer_field_jacobian.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! Pointwise |B| and Boozer generating components with their')
    call w%line('! Jacobian, included by src/boozer_vmec_ad.f90. Output x_y is')
    call w%line('! the partial derivative of output x with respect to input y.')
    call w%emit('boozer_field_jacobian', [character(8) :: inputs, 'athetas'], &
                names(1:n), roots(1:n))
    call w%close()
end program gen_boozer_field_jacobian
