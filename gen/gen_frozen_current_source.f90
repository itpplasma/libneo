!> Pointwise leaves of the frozen-current source in VMEC coordinates
!> (s, theta, varphi), varphi the geometric toroidal angle.
!>
!> vmec_source_field: at one point, with R, Z and their VMEC derivatives,
!> lambda_theta, lambda_varphi and the flux derivatives A_theta' (toroidal
!> flux) and A_phi' (minus the poloidal flux) of spline_vmec_sub,
!>     sqg   = R (R_t Z_s - R_s Z_t),          oriented Jacobian of (s, theta, varphi)
!>     B^t   = -(A_phi' + A_theta' lambda_p)/sqg,
!>     B^p   = A_theta' (1 + lambda_t)/sqg,
!>     B     = B^t e_t + B^p e_p,  e_t = (R_t, 0, Z_t), e_p = (R_p, R, Z_p),
!> returned as physical cylindrical components (B_R, B_phi, B_Z).  These are
!> the contravariant components of compute_field_components transformed from
!> (s, vartheta, varphi), vartheta = theta + lambda, back to (s, theta, varphi).
!>
!> vmec_surface_normal: e_t x e_p in physical cylindrical components, the
!> area vector of a surface s = const per dtheta dvarphi; it points along
!> +e_s when sqg > 0.
!>
!> area_cross_field: g = a x B for the area vector a, the surface term
!> n x B dA of the source, all in physical cylindrical components.
!>
!> cyl_to_cart, cart_to_cyl: rotation of a vector between the cylindrical
!> (R, phi) and Cartesian (x, y) components at c = cos phi, s = sin phi.
program gen_frozen_current_source
    use fortsym_expr, only: expr_t, sym, operator(+), operator(-), &
                            operator(*), operator(/)
    use libneo_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    character(256) :: path
    type(leaf_writer_t) :: w

    path = 'src/generated/frozen_current_source_leaves.inc'
    if (command_argument_count() >= 1) call get_command_argument(1, path)
    call w%open('gen_frozen_current_source', trim(path))
    call w%line('! Generated by gen/gen_frozen_current_source.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! VMEC field and Jacobian, and the surface area vector, in')
    call w%line('! physical cylindrical components, included by')
    call w%line('! src/frozen_current/vmec_equilibrium_source.f90.')
    call field_leaf()
    call normal_leaf()
    call cross_leaf()
    call rotation_leaves()
    call w%close()

contains

    subroutine field_leaf()
        integer, parameter :: nin = 11
        character(8), parameter :: inputs(nin) = [character(8) :: 'r', 'rs', &
                             'rt', 'rp', 'zs', 'zt', 'zp', 'lt', 'lp', 'athetas', 'aphis']
        character(8), parameter :: outputs(4) = [character(8) :: 'sqg', 'br', &
                                                                             'bphi', 'bz']
        type(expr_t) :: x(nin), f(4), sqg, bt, bp
        integer :: k

        do k = 1, nin
            x(k) = sym(trim(inputs(k)))
        end do
        associate (r => x(1), rs => x(2), rt => x(3), rp => x(4), zs => x(5), &
                   zt => x(6), zp => x(7), lt => x(8), lp => x(9), &
                   athetas => x(10), aphis => x(11))
            sqg = r*(rt*zs - rs*zt)
            bt = -(aphis + athetas*lp)/sqg
            bp = athetas*(1 + lt)/sqg
            f(1) = sqg
            f(2) = bt*rt + bp*rp
            f(3) = bp*r
            f(4) = bt*zt + bp*zp
        end associate
        call emit_values('vmec_source_field', inputs, outputs, f)
    end subroutine field_leaf

    subroutine normal_leaf()
        integer, parameter :: nin = 5
        character(8), parameter :: inputs(nin) = [character(8) :: 'r', 'rt', &
                                                                         'rp', 'zt', 'zp']
        character(8), parameter :: outputs(3) = [character(8) :: 'nr', 'nphi', 'nz']
        type(expr_t) :: x(nin), f(3)
        integer :: k

        do k = 1, nin
            x(k) = sym(trim(inputs(k)))
        end do
        associate (r => x(1), rt => x(2), rp => x(3), zt => x(4), zp => x(5))
            f(1) = -r*zt
            f(2) = zt*rp - rt*zp
            f(3) = r*rt
        end associate
        call emit_values('vmec_surface_normal', inputs, outputs, f)
    end subroutine normal_leaf

    subroutine cross_leaf()
        integer, parameter :: nin = 6
        character(8), parameter :: inputs(nin) = [character(8) :: 'ar', 'aphi', &
                                                                 'az', 'br', 'bphi', 'bz']
        character(8), parameter :: outputs(3) = [character(8) :: 'gr', 'gphi', 'gz']
        type(expr_t) :: x(nin), f(3)
        integer :: k

        do k = 1, nin
            x(k) = sym(trim(inputs(k)))
        end do
        associate (ar => x(1), aphi => x(2), az => x(3), br => x(4), &
                   bphi => x(5), bz => x(6))
            f(1) = aphi*bz - az*bphi
            f(2) = az*br - ar*bz
            f(3) = ar*bphi - aphi*br
        end associate
        call emit_values('area_cross_field', inputs, outputs, f)
    end subroutine cross_leaf

    subroutine rotation_leaves()
        character(8), parameter :: cyl(2) = [character(8) :: 'vr', 'vphi']
        character(8), parameter :: cart(2) = [character(8) :: 'vx', 'vy']
        type(expr_t) :: c, s, f(2)

        c = sym('c')
        s = sym('s')
        f(1) = c*sym('vr') - s*sym('vphi')
        f(2) = s*sym('vr') + c*sym('vphi')
        call emit_values('cyl_to_cart', [character(8) :: 'c', 's', cyl], cart, f)
        f(1) = c*sym('vx') + s*sym('vy')
        f(2) = -s*sym('vx') + c*sym('vy')
        call emit_values('cart_to_cyl', [character(8) :: 'c', 's', cart], cyl, f)
    end subroutine rotation_leaves

    subroutine emit_values(name, inputs, outputs, f)
        character(*), intent(in) :: name, inputs(:), outputs(:)
        type(expr_t), intent(in) :: f(:)
        type(expr_t) :: roots(size(f))
        integer :: i

        do i = 1, size(f)
            roots(i) = w%simplify(f(i))
        end do
        call w%emit(name, inputs, outputs, roots)
    end subroutine emit_values
end program gen_frozen_current_source
