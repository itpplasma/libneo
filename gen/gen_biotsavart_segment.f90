program gen_biotsavart_segment
    use fortsym_expr, only: expr_t, sym, num, log, sqrt, &
                            operator(+), operator(-), operator(*), operator(/)
    use fortsym_diff, only: diff
    use fortsym_string, only: itoa
    use libneo_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: writer
    type(expr_t) :: x(3), a(3), b(3), di(3), df(3), dl(3), ri, rf, len, eps
    type(expr_t) :: pot(3), field(3), roots(24)
    character(256) :: path
    character(4) :: args(9), outputs(24)
    integer :: i, j

    path = 'src/generated/biotsavart_segment_leaves.inc'
    if (command_argument_count() > 0) call get_command_argument(1, path)
    do i = 1, 3
        x(i) = sym('x'//itoa(i))
        a(i) = sym('a'//itoa(i))
        b(i) = sym('b'//itoa(i))
        di(i) = x(i) - a(i)
        df(i) = x(i) - b(i)
        dl(i) = b(i) - a(i)
    end do
    ri = sqrt(di(1)*di(1) + di(2)*di(2) + di(3)*di(3))
    rf = sqrt(df(1)*df(1) + df(2)*df(2) + df(3)*df(3))
    len = sqrt(dl(1)*dl(1) + dl(2)*dl(2) + dl(3)*dl(3))
    eps = len/(ri + rf)
    ! Hanson and Hirshman (2002), per unit I/c, as compute_vector_potential and
    ! compute_magnetic_field in src/field/biotsavart.f90.
    do i = 1, 3
        pot(i) = dl(i)/len*log((num(1) + eps)/(num(1) - eps))
    end do
    field(1) = dl(2)*di(3) - dl(3)*di(2)
    field(2) = dl(3)*di(1) - dl(1)*di(3)
    field(3) = dl(1)*di(2) - dl(2)*di(1)
    do i = 1, 3
        field(i) = field(i)/(len*ri*rf)*(num(2)*eps/(num(1) - eps*eps))
    end do
    do i = 1, 3
        args(i) = 'x'//itoa(i)
        args(3 + i) = 'a'//itoa(i)
        args(6 + i) = 'b'//itoa(i)
        outputs(i) = 'pa'//itoa(i)
        outputs(3 + i) = 'pb'//itoa(i)
        roots(i) = pot(i)
        roots(3 + i) = field(i)
        do j = 1, 3
            outputs(3 + 3*i + j) = 'da'//itoa(i)//itoa(j)
            outputs(12 + 3*i + j) = 'db'//itoa(i)//itoa(j)
            roots(3 + 3*i + j) = diff(pot(i), x(j))
            roots(12 + 3*i + j) = diff(field(i), x(j))
        end do
    end do
    call writer%open('gen_biotsavart_segment', trim(path))
    call writer%line('! Generated by gen/gen_biotsavart_segment.f90; do not edit.')
    call writer%line('! FortSym revision: '//fortsym_revision)
    call writer%emit('biotsavart_segment_jacobian', args, outputs, roots)
    call writer%close()
end program gen_biotsavart_segment
