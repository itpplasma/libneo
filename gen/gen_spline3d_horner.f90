program gen_spline3d_horner
    ! Quintic 3D batch spline cell kernels for nq = 1..4 and a runtime nq.
    use libneo_gen_support, only: fortsym_revision, write_spline_leaf
    implicit none
    character(256) :: path
    integer :: unit, nq, order

    path = 'src/generated/spline3d_horner_leaves.inc'
    if (command_argument_count() > 0) call get_command_argument(1, path)
    open (newunit=unit, file=trim(path), status='replace', action='write')
    write (unit, '(a)') '! Generated by gen/gen_spline3d_horner.f90; do not edit.'
    write (unit, '(a)') '! FortSym revision: '//fortsym_revision
    write (unit, '(a)') '! Regenerate with: cmake --build <build> --target '// &
        'regenerate_gen_spline3d_horner'
    do nq = 0, 4
        do order = 0, 2
            call write_spline_leaf(unit, 3, 5, nq, order, .false.)
        end do
        call write_spline_leaf(unit, 3, 5, nq, 2, .true.)
    end do
    close (unit)
end program gen_spline3d_horner
