program gen_lagrange_point
    ! Uniform-stencil Lagrange point kernels behind polylag_3 (cubic) and
    ! neo_polylag_5 (quintic) in three variables: value with gradient, and
    ! the quintic value alone.
    use fortgen_lagrange_emit, only: lagrange_kernel_spec_t, emit_lagrange_kernel
    use fortgen_string, only: str, chars
    use libneo_gen_support, only: fortsym_revision
    implicit none
    character(256) :: path
    integer :: unit

    path = 'src/generated/lagrange_point_leaves.inc'
    if (command_argument_count() > 0) call get_command_argument(1, path)
    open (newunit=unit, file=trim(path), status='replace', action='write')
    write (unit, '(a)') '! Generated by gen/gen_lagrange_point.f90; do not edit.'
    write (unit, '(a)') '! FortSym revision: '//fortsym_revision
    write (unit, '(a)') '! Regenerate with: cmake --build <build> --target '// &
        'regenerate_gen_lagrange_point'
    call leaf('lagrange_point_3d_n4', 3, 4, .true.)
    call leaf('lagrange_point_3d_n6', 3, 6, .true.)
    call leaf('lagrange_value_3d_n6', 3, 6, .false.)
    close (unit)
contains
    subroutine leaf(name, d, n, gradient)
        character(*), intent(in) :: name
        integer, intent(in) :: d, n
        logical, intent(in) :: gradient
        type(lagrange_kernel_spec_t) :: spec
        character(:), allocatable :: message
        logical :: ok

        spec%name = str(name)
        spec%dimension = d
        spec%points = n
        spec%gradient = gradient
        spec%nq = 1
        write (unit, '(a)') ''
        write (unit, '(a)') chars(emit_lagrange_kernel(spec, ok, message))
        if (.not. ok) error stop message
    end subroutine
end program gen_lagrange_point
