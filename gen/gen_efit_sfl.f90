!> Pointwise kernels K6 and K7 of the EFIT straight-field-line construction
!> (src/efit_to_boozer/efit_sfl.f90), Gaussian units, psi per radian.
!>
!> K6 efit_sfl_field, at one (R, Z) with the derivatives of the psi spline,
!> F(psi), the file's 4 pi p'(psi) (mpp) and F F'(psi) (ffp):
!>     B_R = -psi_Z/R, B_Z = psi_R/R, B_phi = F/R, |B| = sqrt(psi_R^2 + psi_Z^2 + F^2)/R,
!>     dstar = psi_RR - psi_R/R + psi_ZZ (Delta* psi), gsrhs = -(R^2 mpp + ffp),
!> so that dstar - gsrhs is the Grad-Shafranov residual.
!>
!> K7 efit_sfl_contour, at one point R = R_0 + rho c, Z = Z_0 + rho s of the ray
!> with direction (c, s) through the magnetic axis, where the flux surface
!> crosses it. psi is oriented so that psi_rho = c psi_R + s psi_Z > 0 and
!> f = |F|:
!>     h  = f rho/(R psi_rho)               (d phi/d theta_g along B, mean = q)
!>     bg = |grad psi|^2 rho/(R psi_rho)    (B_pol . dr/dtheta_g, mean = I)
!>     b  = |B|
!>     jc = R rho/psi_rho                   (Hamada: J_P dtheta_P/dtheta_g = R^2 h/f)
!>     jb = (|grad psi|^2 + f^2) rho/(R psi_rho f)   (Boozer: J_P B^2 dtheta_P/dtheta_g)
!> Each leaf returns its outputs and their partial derivatives with respect to
!> the inputs.
program gen_efit_sfl
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, sqrt, operator(+), operator(-), &
                            operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use libneo_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    character(256) :: path
    type(leaf_writer_t) :: w
    type(arena_t), target :: arena

    path = 'src/generated/efit_sfl_leaves.inc'
    if (command_argument_count() >= 1) call get_command_argument(1, path)
    call arena%init()
    call w%open(arena, 'gen_efit_sfl', trim(path))
    call w%line('! Generated by gen/gen_efit_sfl.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! EFIT field (K6) and flux-surface contour integrands (K7) with')
    call w%line('! their Jacobians, included by src/efit_to_boozer/efit_sfl.f90.')
    call w%line('! Output x_y is the partial derivative of output x with respect to y.')
    call field_kernel()
    call contour_kernel()
    call w%close()

contains

    subroutine field_kernel()
        integer, parameter :: nin = 9, nout = 6
        character(8), parameter :: inputs(nin) = [character(8) :: 'r', 'pr', 'pz', &
            'prr', 'prz', 'pzz', 'f', 'mpp', 'ffp']
        character(8), parameter :: outputs(nout) = [character(8) :: 'br', 'bz', &
            'bphi', 'b', 'dstar', 'gsrhs']
        type(expr_t) :: x(nin), f(nout)
        integer :: k

        do k = 1, nin
            x(k) = sym(arena, trim(inputs(k)))
        end do
        associate (r => x(1), pr => x(2), pz => x(3), prr => x(4), &
                   pzz => x(6), ff => x(7), mpp => x(8), ffp => x(9))
            f(1) = -pz/r
            f(2) = pr/r
            f(3) = ff/r
            f(4) = sqrt(pr**2 + pz**2 + ff**2)/r
            f(5) = prr - pr/r + pzz
            f(6) = -(r**2*mpp + ffp)
        end associate
        call emit_leaf('efit_sfl_field', inputs, outputs, x, f)
    end subroutine field_kernel

    subroutine contour_kernel()
        integer, parameter :: nin = 7, nout = 5
        character(8), parameter :: inputs(nin) = [character(8) :: 'rho', 'c', 's', &
            'r', 'pr', 'pz', 'f']
        character(8), parameter :: outputs(nout) = [character(8) :: 'h', 'bg', 'b', &
            'jc', 'jb']
        type(expr_t) :: x(nin), f(nout), prho, g2
        integer :: k

        do k = 1, nin
            x(k) = sym(arena, trim(inputs(k)))
        end do
        associate (rho => x(1), c => x(2), s => x(3), r => x(4), pr => x(5), &
                   pz => x(6), ff => x(7))
            prho = c*pr + s*pz
            g2 = pr**2 + pz**2
            f(1) = ff*rho/(r*prho)
            f(2) = g2*rho/(r*prho)
            f(3) = sqrt(g2 + ff**2)/r
            f(4) = r*rho/prho
            f(5) = (g2 + ff**2)*rho/(r*prho*ff)
        end associate
        call emit_leaf('efit_sfl_contour', inputs, outputs, x, f)
    end subroutine contour_kernel

    subroutine emit_leaf(name, inputs, outputs, x, f)
        character(*), intent(in) :: name, inputs(:), outputs(:)
        type(expr_t), intent(in) :: x(:), f(:)
        type(expr_t), allocatable :: roots(:)
        character(16), allocatable :: names(:)
        integer :: i, k, n

        allocate (roots(size(f)*(size(x) + 1)), names(size(f)*(size(x) + 1)))
        n = 0
        do i = 1, size(f)
            n = n + 1
            roots(n) = w%simplify(f(i))
            names(n) = outputs(i)
            do k = 1, size(x)
                n = n + 1
                roots(n) = w%simplify(diff(f(i), x(k)))
                names(n) = trim(outputs(i))//'_'//trim(inputs(k))
            end do
        end do
        call w%emit(name, inputs, names(1:n), roots(1:n))
    end subroutine emit_leaf
end program gen_efit_sfl
