program gen_spline1d_horner
    ! Quintic single-quantity 1D batch spline cell kernels up to the second and
    ! third derivative.
    use libneo_gen_support, only: fortsym_revision, write_spline_leaf
    implicit none
    character(256) :: path
    integer :: unit, order

    path = 'src/generated/spline1d_horner_leaves.inc'
    if (command_argument_count() > 0) call get_command_argument(1, path)
    open (newunit=unit, file=trim(path), status='replace', action='write')
    write (unit, '(a)') '! Generated by gen/gen_spline1d_horner.f90; do not edit.'
    write (unit, '(a)') '! FortSym revision: '//fortsym_revision
    write (unit, '(a)') '! Regenerate with: cmake --build <build> --target '// &
        'regenerate_gen_spline1d_horner'
    do order = 2, 3
        call write_spline_leaf(unit, 1, 5, 1, order, .false.)
    end do
    close (unit)
end program gen_spline1d_horner
