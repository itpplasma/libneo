!> Pointwise kernels of the straight-field-line routes beyond the covariant
!> Boozer route (src/boozer_hybrid.f90, routes R2 to R4 of the sfl design).
!>
!> All three leaves return their outputs with the full Jacobian with respect
!> to their inputs, at psi' = 1 (psi' scales B linearly and is applied by the
!> caller), in VMEC coordinates (s, theta, phi) with the cylindrical metric of
!> (R, phi, Z):
!>
!> sfl_route_weight (inputs r, rs, rt, zs, zt, b):
!>     sqgv  = R (R_t Z_s - R_s Z_t)            the VMEC Jacobian sqrt(g)_V,
!>     sqgvb = sqrt(g)_V |B|^2,
!>   the densities of the magnetic differential equations of the Jacobian
!>   routes in the PEST measure: J_P (1 + lambda_t) = sqrt(g)_V (Hamada I) and
!>   J_P B^2 (1 + lambda_t) = sqrt(g)_V B^2 (Boozer, Jacobian route).
!>
!> sfl_radial_field (inputs r, rs, rt, rp, zs, zt, zp, lt, lp, iota and the
!> radial derivatives rss, rst, rsp, zss, zst, zsp, lst, lsp, iotap):
!>     bs  = g_st B^theta + g_sp B^phi          covariant B_s,
!>     dbt = d/ds B_theta, dbp = d/ds B_phi     at fixed VMEC angles,
!>   with B^theta = (iota - lambda_p)/sqrt(g)_V, B^phi = (1 + lambda_t)/sqrt(g)_V
!>   and the covariant B_theta, B_phi of gen_boozer_hybrid_field. The radial
!>   derivative is the total derivative through every input (r -> rs,
!>   rs -> rss, rt -> rst, rp -> rsp, zs -> zss, zt -> zst, zp -> zsp,
!>   lt -> lst, lp -> lsp, iota -> iotap).
!>
!> sfl_beta (inputs bs, bt, bp, lt, lp, ls, nu, nut, nup, nus, iota, iotap):
!>     beta = B_s + B_theta d_s theta|_B + B_phi d_s phi|_B,
!>   the radial covariant component in Boozer coordinates
!>   theta_B = theta + lambda + iota nu, phi_B = phi + nu, where
!>   [[a, b], [c, e]] (d_s theta, d_s phi)|_B = -(t_s, nu_s) with
!>   a = 1 + lambda_t + iota nu_t, b = lambda_p + iota nu_p, c = nu_t,
!>   e = 1 + nu_p and t_s = lambda_s + iota' nu + iota nu_s.
program gen_sfl_route_kernels
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, operator(+), operator(-), &
                            operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use libneo_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: w
    type(arena_t), target :: arena
    character(256) :: path

    path = 'src/generated/sfl_route_kernels_leaves.inc'
    if (command_argument_count() >= 1) call get_command_argument(1, path)

    call arena%init()
    call w%open(arena, 'gen_sfl_route_kernels', trim(path))
    call w%line('! Generated by gen/gen_sfl_route_kernels.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! Pointwise kernels of the SFL routes (weights of the magnetic')
    call w%line('! differential equation, radial field derivatives, Boozer beta) at')
    call w%line('! psi'' = 1 with their Jacobian, included by src/boozer_hybrid.f90.')
    call w%line('! Output x_y is the partial derivative of output x with respect to y.')
    call emit_weight()
    call emit_radial()
    call emit_beta()
    call w%close()

contains

    subroutine emit_jacobian(name, inputs, outputs, x, f)
        character(*), intent(in) :: name, inputs(:), outputs(:)
        type(expr_t), intent(in) :: x(:), f(:)
        type(expr_t), allocatable :: roots(:)
        character(16), allocatable :: names(:)
        integer :: i, k, n

        allocate (roots(size(f)*(size(x) + 1)), names(size(f)*(size(x) + 1)))
        n = 0
        do i = 1, size(f)
            n = n + 1
            roots(n) = w%simplify(f(i))
            names(n) = outputs(i)
            do k = 1, size(x)
                n = n + 1
                roots(n) = w%simplify(diff(f(i), x(k)))
                names(n) = trim(outputs(i))//'_'//trim(inputs(k))
            end do
        end do
        call w%emit(name, inputs, names(1:n), roots(1:n))
    end subroutine emit_jacobian

    subroutine emit_weight()
        integer, parameter :: nin = 6
        character(8), parameter :: inputs(nin) = [character(8) :: 'r', 'rs', 'rt', &
            'zs', 'zt', 'b']
        character(8), parameter :: outputs(2) = [character(8) :: 'sqgv', 'sqgvb']
        type(expr_t) :: x(nin), f(2)
        integer :: k

        do k = 1, nin
            x(k) = sym(arena, trim(inputs(k)))
        end do
        f(1) = x(1)*(x(3)*x(4) - x(2)*x(5))
        f(2) = f(1)*x(6)**2
        call emit_jacobian('sfl_route_weight', inputs, outputs, x, f)
    end subroutine emit_weight

    subroutine emit_radial()
        integer, parameter :: nin = 19, nbase = 10
        character(8), parameter :: inputs(nin) = [character(8) :: 'r', 'rs', 'rt', &
            'rp', 'zs', 'zt', 'zp', 'lt', 'lp', 'iota', 'rss', 'rst', 'rsp', 'zss', &
            'zst', 'zsp', 'lst', 'lsp', 'iotap']
        character(8), parameter :: outputs(3) = [character(8) :: 'bs', 'dbt', 'dbp']
        !> index of the radial derivative of each base input
        integer, parameter :: dsof(nbase) = [2, 11, 12, 13, 14, 15, 16, 17, 18, 19]
        type(expr_t) :: x(nin), f(3), gtt, gtp, gpp, gst, gsp, sqg, bu, bv, bcu, bcv
        integer :: k

        do k = 1, nin
            x(k) = sym(arena, trim(inputs(k)))
        end do
        associate (r => x(1), rs => x(2), rt => x(3), rp => x(4), zs => x(5), &
                   zt => x(6), zp => x(7), lt => x(8), lp => x(9), iota => x(10))
            gtt = rt**2 + zt**2
            gtp = rt*rp + zt*zp
            gpp = r**2 + rp**2 + zp**2
            gst = rs*rt + zs*zt
            gsp = rs*rp + zs*zp
            sqg = r*(rt*zs - rs*zt)
            bu = (iota - lp)/sqg
            bv = (1 + lt)/sqg
            bcu = gtt*bu + gtp*bv
            bcv = gtp*bu + gpp*bv
            f(1) = gst*bu + gsp*bv
        end associate
        f(2) = total_ds(bcu, x, dsof)
        f(3) = total_ds(bcv, x, dsof)
        call emit_jacobian('sfl_radial_field', inputs, outputs, x, f)
    end subroutine emit_radial

    !> Total radial derivative of e through the base inputs x(1:size(dsof)),
    !> the derivative of x(j) being x(dsof(j)).
    function total_ds(e, x, dsof) result(d)
        type(expr_t), intent(in) :: e, x(:)
        integer, intent(in) :: dsof(:)
        type(expr_t) :: d
        integer :: j

        d = diff(e, x(1))*x(dsof(1))
        do j = 2, size(dsof)
            d = d + diff(e, x(j))*x(dsof(j))
        end do
    end function total_ds

    subroutine emit_beta()
        integer, parameter :: nin = 12
        character(8), parameter :: inputs(nin) = [character(8) :: 'bs', 'bt', 'bp', &
            'lt', 'lp', 'ls', 'nu', 'nut', 'nup', 'nus', 'iota', 'iotap']
        character(8), parameter :: outputs(1) = [character(8) :: 'beta']
        type(expr_t) :: x(nin), f(1), a, b, c, e, det, ts, ths, phs
        integer :: k

        do k = 1, nin
            x(k) = sym(arena, trim(inputs(k)))
        end do
        associate (bs => x(1), bt => x(2), bp => x(3), lt => x(4), lp => x(5), &
                   ls => x(6), nu => x(7), nut => x(8), nup => x(9), nus => x(10), &
                   iota => x(11), iotap => x(12))
            a = 1 + lt + iota*nut
            b = lp + iota*nup
            c = nut
            e = 1 + nup
            det = a*e - b*c
            ts = ls + iotap*nu + iota*nus
            ths = -(e*ts - b*nus)/det
            phs = -(a*nus - c*ts)/det
            f(1) = bs + bt*ths + bp*phs
        end associate
        call emit_jacobian('sfl_beta', inputs, outputs, x, f)
    end subroutine emit_beta
end program gen_sfl_route_kernels
