!> Pointwise field kernel K1/K3 of the hybrid VMEC -> Boozer construction.
!>
!> At one point of the VMEC angle grid, from R, Z, lambda, their VMEC-coordinate
!> derivatives and iota (Hirshman & Whitson 1983):
!>     sqrt(g)_V = R (R_t Z_s - R_s Z_t),
!>     g_tt = R_t^2 + Z_t^2, g_tp = R_t R_p + Z_t Z_p, g_pp = R^2 + R_p^2 + Z_p^2,
!>     B^theta = psi' (iota - lambda_p)/sqrt(g)_V, B^phi = psi' (1 + lambda_t)/sqrt(g)_V,
!>     B_theta = g_tt B^theta + g_tp B^phi, B_phi = g_tp B^theta + g_pp B^phi,
!>     |B| = sqrt(B^theta B_theta + B^phi B_phi),
!>     |grad s| = sqrt((g_tt g_pp - g_tp^2)/sqrt(g)_V^2).
!> The toroidal flux derivative psi' scales B linearly and is applied by the
!> caller, so the kernel is evaluated at psi' = 1. The leaf returns the four
!> outputs (b, bt, bp, gss) and their partial derivatives with respect to the
!> ten inputs (r, rs, rt, rp, zs, zt, zp, lt, lp, iota).
program gen_boozer_hybrid_field
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, sqrt, operator(+), operator(-), &
                            operator(*), operator(/), operator(**)
    use fortsym_diff, only: diff
    use libneo_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    integer, parameter :: nin = 10, nout = 4
    character(8), parameter :: inputs(nin) = [character(8) :: 'r', 'rs', 'rt', &
        'rp', 'zs', 'zt', 'zp', 'lt', 'lp', 'iota']
    character(8), parameter :: outputs(nout) = [character(8) :: 'b', 'bt', 'bp', 'gss']
    type(leaf_writer_t) :: w
    type(arena_t), target :: arena
    type(expr_t) :: x(nin), gtt, gtp, gpp, sqg, bu, bv, bcu, bcv, f(nout)
    type(expr_t) :: roots(nout*(nin + 1))
    character(16) :: names(nout*(nin + 1))
    character(256) :: path
    integer :: i, k, n

    path = 'src/generated/boozer_hybrid_field_leaves.inc'
    if (command_argument_count() >= 1) call get_command_argument(1, path)

    call arena%init()
    do k = 1, nin
        x(k) = sym(arena, trim(inputs(k)))
    end do
    associate (r => x(1), rs => x(2), rt => x(3), rp => x(4), zs => x(5), &
               zt => x(6), zp => x(7), lt => x(8), lp => x(9), iota => x(10))
        gtt = rt**2 + zt**2
        gtp = rt*rp + zt*zp
        gpp = r**2 + rp**2 + zp**2
        sqg = r*(rt*zs - rs*zt)
        bu = (iota - lp)/sqg
        bv = (1 + lt)/sqg
        bcu = gtt*bu + gtp*bv
        bcv = gtp*bu + gpp*bv
        f(1) = sqrt(bu*bcu + bv*bcv)
        f(2) = bcu
        f(3) = bcv
        f(4) = sqrt((gtt*gpp - gtp**2)/sqg**2)
    end associate

    call w%open(arena, 'gen_boozer_hybrid_field', trim(path))
    n = 0
    do i = 1, nout
        n = n + 1
        roots(n) = w%simplify(f(i))
        names(n) = outputs(i)
        do k = 1, nin
            n = n + 1
            roots(n) = w%simplify(diff(f(i), x(k)))
            names(n) = trim(outputs(i))//'_'//trim(inputs(k))
        end do
    end do

    call w%line('! Generated by gen/gen_boozer_hybrid_field.f90; do not edit.')
    call w%line('! FortSym revision: '//fortsym_revision)
    call w%line('! Pointwise |B|, covariant B_theta, B_phi (VMEC angles) and |grad s|')
    call w%line('! at psi'' = 1 with their Jacobian, included by src/boozer_hybrid.f90.')
    call w%line('! Output x_y is the partial derivative of output x with respect to y.')
    call w%emit('boozer_hybrid_field', inputs, names(1:n), roots(1:n))
    call w%close()
end program gen_boozer_hybrid_field
