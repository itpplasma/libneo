program gen_cylindrical_vector_jacobian
    use fortsym_expr, only: expr_t, sym, num, sqrt, &
                            operator(+), operator(-), operator(*), operator(/)
    use fortsym_diff, only: diff
    use libneo_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: writer
    type(expr_t) :: x, y, r, cart(3), comp(3), dr(3), dp(3), dz(3), roots(12)
    character(256) :: path
    character(6) :: names(3), args(14), outputs(12)
    character(1) :: cartesian(3)
    integer :: i, j, k

    path = 'src/generated/cylindrical_vector_jacobian_leaves.inc'
    if (command_argument_count() > 0) call get_command_argument(1, path)
    names = [character(6) :: 'vr', 'vp', 'vz']
    cartesian = ['x', 'y', 'z']
    x = sym('x')
    y = sym('y')
    r = sqrt(x*x + y*y)
    ! Physical cylindrical components (V_R, V_phi, V_Z) and their derivatives
    ! along R, phi and Z at the Cartesian point (x, y, z).
    do k = 1, 3
        comp(k) = sym(trim(names(k)))
        dr(k) = sym(trim(names(k))//'_r')
        dp(k) = sym(trim(names(k))//'_p')
        dz(k) = sym(trim(names(k))//'_z')
    end do
    cart = [x/r*comp(1) - y/r*comp(2), y/r*comp(1) + x/r*comp(2), comp(3)]
    do i = 1, 3
        roots(i) = cart(i)
        roots(3*i + 1) = diff(cart(i), x)
        roots(3*i + 2) = diff(cart(i), y)
        roots(3*i + 3) = num(0)
        do k = 1, 3
            roots(3*i + 1) = roots(3*i + 1) &
                             + diff(cart(i), comp(k))*(dr(k)*x/r - dp(k)*y/(r*r))
            roots(3*i + 2) = roots(3*i + 2) &
                             + diff(cart(i), comp(k))*(dr(k)*y/r + dp(k)*x/(r*r))
            roots(3*i + 3) = roots(3*i + 3) + diff(cart(i), comp(k))*dz(k)
        end do
    end do
    args(1:2) = [character(6) :: 'x', 'y']
    do k = 1, 3
        args(2 + k) = names(k)
        args(5 + k) = trim(names(k))//'_r'
        args(8 + k) = trim(names(k))//'_p'
        args(11 + k) = trim(names(k))//'_z'
    end do
    do i = 1, 3
        outputs(i) = 'c'//cartesian(i)
        do j = 1, 3
            outputs(3*i + j) = 'd'//cartesian(i)//cartesian(j)
        end do
    end do
    call writer%open('gen_cylindrical_vector_jacobian', trim(path))
    do i = 1, size(roots)
        roots(i) = writer%simplify(roots(i))
    end do
    call writer%line('! Generated by gen/gen_cylindrical_vector_jacobian.f90; '// &
                     'do not edit.')
    call writer%line('! FortSym revision: '//fortsym_revision)
    call writer%emit('cylindrical_vector_jacobian', args, outputs, roots)
    call writer%close()
end program gen_cylindrical_vector_jacobian
