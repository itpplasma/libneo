program gen_guiding_centre_field
    ! Guiding-centre field quantities at a point of a curvilinear chart u from
    ! the chart's tangent basis e(i, j) = dx_i/du_j, the Cartesian field b and
    ! its Jacobian db(i, j) = db_i/dx_j: |B|, sqrt(g) = det e, d_j log|B|, the
    ! covariant and contravariant components of h = B/|B| and the
    ! contravariant components of curl h.
    use fortsym_expr, only: expr_t, sym, num, sqrt, &
                            operator(+), operator(-), operator(*), operator(/)
    use fortsym_string, only: itoa
    use libneo_gen_support, only: leaf_writer_t, fortsym_revision
    implicit none
    type(leaf_writer_t) :: writer
    type(expr_t) :: e(3, 3), b(3), db(3, 3), inv(3, 3), det, bmod, grad(3), &
                    curl_b(3), curl_h(3), roots(14)
    character(256) :: path
    character(6) :: args(21), outputs(14)
    integer :: i, j, k

    path = 'src/generated/guiding_centre_field_leaves.inc'
    if (command_argument_count() > 0) call get_command_argument(1, path)
    do i = 1, 3
        b(i) = sym('b'//itoa(i))
        do j = 1, 3
            e(i, j) = sym('e'//itoa(i)//itoa(j))
            db(i, j) = sym('db'//itoa(i)//itoa(j))
        end do
    end do
    det = e(1, 1)*(e(2, 2)*e(3, 3) - e(2, 3)*e(3, 2)) &
          - e(1, 2)*(e(2, 1)*e(3, 3) - e(2, 3)*e(3, 1)) &
          + e(1, 3)*(e(2, 1)*e(3, 2) - e(2, 2)*e(3, 1))
    ! inv(i, k) = du_i/dx_k, the rows are the contravariant basis vectors.
    inv(1, 1) = (e(2, 2)*e(3, 3) - e(2, 3)*e(3, 2))/det
    inv(1, 2) = (e(1, 3)*e(3, 2) - e(1, 2)*e(3, 3))/det
    inv(1, 3) = (e(1, 2)*e(2, 3) - e(1, 3)*e(2, 2))/det
    inv(2, 1) = (e(2, 3)*e(3, 1) - e(2, 1)*e(3, 3))/det
    inv(2, 2) = (e(1, 1)*e(3, 3) - e(1, 3)*e(3, 1))/det
    inv(2, 3) = (e(1, 3)*e(2, 1) - e(1, 1)*e(2, 3))/det
    inv(3, 1) = (e(2, 1)*e(3, 2) - e(2, 2)*e(3, 1))/det
    inv(3, 2) = (e(1, 2)*e(3, 1) - e(1, 1)*e(3, 2))/det
    inv(3, 3) = (e(1, 1)*e(2, 2) - e(1, 2)*e(2, 1))/det
    bmod = sqrt(b(1)*b(1) + b(2)*b(2) + b(3)*b(3))
    do k = 1, 3
        grad(k) = (b(1)*db(1, k) + b(2)*db(2, k) + b(3)*db(3, k))/bmod
    end do
    curl_b = [db(3, 2) - db(2, 3), db(1, 3) - db(3, 1), db(2, 1) - db(1, 2)]
    ! curl(B/|B|) = curl B/|B| - grad|B| x B/|B|^2
    curl_h(1) = curl_b(1)/bmod - (grad(2)*b(3) - grad(3)*b(2))/(bmod*bmod)
    curl_h(2) = curl_b(2)/bmod - (grad(3)*b(1) - grad(1)*b(3))/(bmod*bmod)
    curl_h(3) = curl_b(3)/bmod - (grad(1)*b(2) - grad(2)*b(1))/(bmod*bmod)
    roots(1) = bmod
    roots(2) = det
    do j = 1, 3
        roots(2 + j) = (grad(1)*e(1, j) + grad(2)*e(2, j) + grad(3)*e(3, j))/bmod
        roots(5 + j) = (b(1)*e(1, j) + b(2)*e(2, j) + b(3)*e(3, j))/bmod
        roots(8 + j) = (inv(j, 1)*b(1) + inv(j, 2)*b(2) + inv(j, 3)*b(3))/bmod
        roots(11 + j) = inv(j, 1)*curl_h(1) + inv(j, 2)*curl_h(2) + inv(j, 3)*curl_h(3)
    end do
    k = 0
    do i = 1, 3
        do j = 1, 3
            k = k + 1
            args(k) = 'e'//itoa(i)//itoa(j)
            args(12 + k) = 'db'//itoa(i)//itoa(j)
        end do
        args(9 + i) = 'b'//itoa(i)
    end do
    outputs(1:2) = [character(6) :: 'bmod', 'sqrtg']
    do j = 1, 3
        outputs(2 + j) = 'bder'//itoa(j)
        outputs(5 + j) = 'hcov'//itoa(j)
        outputs(8 + j) = 'hctr'//itoa(j)
        outputs(11 + j) = 'hcurl'//itoa(j)
    end do
    call writer%open('gen_guiding_centre_field', trim(path))
    call writer%line('! Generated by gen/gen_guiding_centre_field.f90; do not edit.')
    call writer%line('! FortSym revision: '//fortsym_revision)
    call writer%emit('guiding_centre_field', args, outputs, roots)
    call writer%close()
end program gen_guiding_centre_field
